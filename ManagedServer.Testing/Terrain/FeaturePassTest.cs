using ManagedServer.Terrain;
using ManagedServer.Terrain.Features;
using Minecraft.Data.Blocks;
using Minecraft.Data.Generated;
using Minecraft.Implementations.Server.Terrain;
using Minecraft.Implementations.Server.Terrain.Generation;
using Minecraft.Registry;
using Minecraft.Schemas;
using Minecraft.Schemas.Chunks;
using Minecraft.Schemas.Vec;

namespace ManagedServer.Testing.Terrain;

/// <summary>
/// That the decoration pass runs, puts vegetation on the ground, and does it the same way twice.
/// </summary>
/// <remarks>
/// Deliberately not a conformance fixture. What a chunk's trees look like is decided by the order the
/// random is drawn in across every feature in the chunk, and there is no harness for that; what this
/// pins is the properties that would make such a harness meaningless if they were broken.
/// <p/>
/// The reproducibility test is the load bearing one. The whole seeding scheme exists so that a chunk
/// generates identically whatever order chunks are asked for and on however many threads, and the
/// failure mode is a world that looks fine and differs between two runs.
/// </remarks>
[TestFixture]
public class FeaturePassTest {
    private const long Seed = 1234567890L;

    /// <summary>Somewhere with trees on it, rather than an ocean.</summary>
    private static readonly Vec2<int>[] Chunks = [
        new(0, 0), new(1, 0), new(0, 1), new(1, 1), new(4, 4), new(-3, 2), new(7, -5), new(-6, -6)
    ];

    [Test]
    public void TerrainIsBareWithoutTheFeaturePass() {
        VanillaTerrainGenerator generator = VanillaTerrainGenerator.Overworld(VanillaPack.Source, Seed);
        Assert.That(generator.HasFeatures, Is.False,
            "The feature pass has to be opt in, like everything else in this framework.");

        Dictionary<Identifier, int> counts = Generate(generator, Chunks);

        Assert.That(counts.Keys.Where(IsLog), Is.Empty, "Bare terrain grew a tree.");
        Assert.That(counts.Keys.Where(IsPlant), Is.Empty, "Bare terrain grew a plant.");
    }

    [Test]
    public void TheFeaturePassPlacesTreesAndPlants() {
        Dictionary<Identifier, int> counts =
            Generate(VanillaTerrainGenerator.Overworld(VanillaPack.Source, Seed).WithFeatures(), Chunks);

        Assert.Multiple(() => {
            Assert.That(counts.Keys.Count(IsLog), Is.GreaterThan(0), "No logs were placed.");
            Assert.That(counts.Keys.Count(IsLeaves), Is.GreaterThan(0), "No leaves were placed.");
            Assert.That(counts.Keys.Count(IsPlant), Is.GreaterThan(0), "No plants were placed.");
        });
    }

    /// <summary>
    /// Ores are the one feature family whose absence is invisible from the surface, so they get their
    /// own check.
    /// </summary>
    [Test]
    public void TheFeaturePassPlacesOres() {
        Dictionary<Identifier, int> counts =
            Generate(VanillaTerrainGenerator.Overworld(VanillaPack.Source, Seed).WithFeatures(), Chunks);

        Assert.That(counts.Keys.Count(id => id.Key.EndsWith("_ore", StringComparison.Ordinal)),
            Is.GreaterThan(0), "No ores were placed.");
    }

    /// <summary>
    /// A chunk's own decoration is the same whatever order the chunks were asked for.
    /// </summary>
    /// <remarks>
    /// Each chunk is generated by a provider of its own, so nothing forked in from a neighbour can
    /// reach it and what is measured is the chunk's own pass alone. That is the property the seeding
    /// scheme is for, and the reversed order is what would catch a feature seeded from a running
    /// sequence rather than from the chunk position.
    /// <p/>
    /// What a <b>neighbour</b> forks into a chunk is a different question and deliberately not asked
    /// here: a fork lands immediately if the target is loaded and parks until it is otherwise, so how
    /// much of a border tree has arrived depends on how far the world has got. Convergence is the
    /// fork queue's property and <c>ForkRaceTest</c> is where it is pinned.
    /// </remarks>
    [Test]
    public void ADecoratedChunkIsTheSameWhateverOrderChunksAreAskedFor() {
        Dictionary<Identifier, int> forwards = GenerateIndependently(Chunks);
        Dictionary<Identifier, int> backwards = GenerateIndependently(Chunks.Reverse().ToArray());

        Assert.That(backwards, Is.EquivalentTo(forwards));
    }

    /// <summary>A different seed gives a different world, so the seed reaches the feature pass at all.</summary>
    [Test]
    public void ADifferentSeedDecoratesDifferently() {
        Dictionary<Identifier, int> first =
            Generate(VanillaTerrainGenerator.Overworld(VanillaPack.Source, Seed).WithFeatures(), Chunks);

        Dictionary<Identifier, int> second =
            Generate(VanillaTerrainGenerator.Overworld(VanillaPack.Source, Seed + 1).WithFeatures(), Chunks);

        Assert.That(second, Is.Not.EquivalentTo(first));
    }

    /// <summary>Each chunk through a provider of its own, so no fork from a neighbour can land.</summary>
    private static Dictionary<Identifier, int> GenerateIndependently(IReadOnlyList<Vec2<int>> chunks) {
        Dictionary<Identifier, int> counts = [];

        foreach (Vec2<int> pos in chunks) {
            foreach ((Identifier block, int count) in
                Generate(VanillaTerrainGenerator.Overworld(VanillaPack.Source, Seed).WithFeatures(), [pos])) {

                counts[block] = counts.GetValueOrDefault(block) + count;
            }
        }

        return counts;
    }

    /// <summary>
    /// A block forked into a neighbour reads back, rather than the neighbour's air.
    /// </summary>
    /// <remarks>
    /// A decorator's whole shape is "look at what the tree placed, then fill the gaps beside it", and
    /// it asks the level rather than the sets it was handed. So a level that forgets its own forked
    /// writes tells a jungle tree that its canopy across the border is empty air, and the vine
    /// decorators fill it in: hanging vines land <b>through</b> the leaves instead of off them, four
    /// blocks at a time. Only the terrain a neighbour has not generated may read as air.
    /// </remarks>
    [Test]
    public void AForkedBlockReadsBackRatherThanAnsweringAir() {
        ChunkColumn column = new(-64, 320, Block.Air.StateId);
        ChunkFeatureLevel level = new(column, new DiscardingSetter(), (_, _, _) => null!,
            VanillaRegistry.Data, 0, 0, -64, 320, 63, Seed, new LegacyRandomSource(Seed));

        // One block east of the chunk, which is where a canopy overhanging the border lands.
        const int outsideX = 16;

        Assert.That(level.IsLoaded(outsideX, 0), Is.False, "The test position has to be outside.");
        Assert.That(level.GetState(outsideX, 70, 0), Is.EqualTo(Block.Air.StateId),
            "Terrain that has not been generated reads as air.");

        level.SetState(outsideX, 70, 0, Block.JungleLeaves.StateId);

        Assert.That(level.GetState(outsideX, 70, 0), Is.EqualTo(Block.JungleLeaves.StateId),
            "A forked block read back as air, so a decorator would overwrite it.");

        column.Release();
    }

    /// <summary>A fork with nowhere to put anything, for a level under test on its own.</summary>
    private sealed class DiscardingSetter : IBlockSetter {
        public void SetBlock(int x, int y, int z, IBlock block) { }
        public void SetBlock(Vec3<int> pos, IBlock block) { }
        public void SetBlockState(int x, int y, int z, uint stateId) { }
        public void SetBlockState(Vec3<int> pos, uint stateId) { }
    }

    /// <summary>
    /// Every feature type the vanilla data names is either transcribed or on the list of ones that are
    /// not, with a reason.
    /// </summary>
    /// <remarks>
    /// This is what turns a new feature type upstream into a failing test rather than into a world
    /// quietly missing something. It cannot be a check that the list is empty, because the list is
    /// deliberately non empty; what it checks is that nothing is missing without having been named.
    /// </remarks>
    [Test]
    public void EveryUntranscribedFeatureTypeIsNamed() {
        VanillaFeatureData data = VanillaFeatureData.Load(VanillaPack.Source);

        // Every biome in the pack rather than one dimension's, so a feature only the end or the nether
        // asks for is resolved too and reports itself if it cannot be built.
        _ = data.TableFor(data.Biomes);

        List<string> unnamed = [];
        foreach (string type in data.Skipped.Keys) {
            // A name with a space in it is not a feature type: it is either an outer feature that
            // could not be built because something nested inside it was skipped, or a named feature
            // that could not be resolved. Both report the real reason under its own type.
            if (!FeatureParser.NotTranscribed.ContainsKey(type) && !type.Contains(' ')) {
                unnamed.Add(type);
            }
        }

        Assert.That(unnamed, Is.Empty,
            "A feature type was skipped without being on the not-transcribed list.");
    }

    /// <summary>
    /// Every feature, placed feature and block state provider the pack registers parses, whether or
    /// not a biome asks for it.
    /// </summary>
    /// <remarks>
    /// The biome tables only reach what a biome names, which leaves out everything a structure, a
    /// bone meal action or another feature's nested reference reaches, and those fail at the moment
    /// they are first placed rather than at load.
    /// </remarks>
    [Test]
    public void EveryFeatureInThePackParses() {
        VanillaFeatureData data = VanillaFeatureData.Load(VanillaPack.Source);

        foreach (Identifier id in data.BlockStateProviders) {
            Assert.DoesNotThrow(() => data.Provider(id), $"block state provider {id}");
        }

        foreach (Identifier id in data.Features) {
            Assert.DoesNotThrow(() => data.Feature(id), $"feature {id}");
        }

        foreach (Identifier id in data.PlacedFeatures) {
            Assert.DoesNotThrow(() => data.Placed(id), $"placed feature {id}");
        }

        List<string> unnamed = data.Skipped.Keys
            .Where(type => !FeatureParser.NotTranscribed.ContainsKey(type) && !type.Contains(' ')).ToList();
        Assert.That(unnamed, Is.Empty, "A feature type was skipped without being on the not-transcribed list.");
    }

    /// <summary>How many blocks of each kind a set of chunks came out holding.</summary>
    private static Dictionary<Identifier, int> Generate(VanillaTerrainGenerator generator,
        IReadOnlyList<Vec2<int>> chunks) {

        MinecraftRegistry registry = VanillaRegistry.Data;
        GeneratorTerrainProvider provider = generator.AsProvider();
        provider.Attach(new CountingHost());

        Dictionary<Identifier, int> counts = [];

        foreach (Vec2<int> pos in chunks) {
            ChunkData chunk = new(384) { ChunkX = pos.X, ChunkZ = pos.Y, MinY = -64 };
            provider.GetChunk(ref chunk);

            for (int x = 0; x < 16; x++) {
                for (int z = 0; z < 16; z++) {
                    // Protocol y, which is what the chunk is indexed by, unlike everything on the
                    // generation API.
                    for (int y = 0; y < 384; y++) {
                        uint state = chunk.GetBlock(x, y, z);
                        IBlock block = registry.Blocks.GetByStateId(state);

                        if (block.Air) {
                            continue;
                        }

                        counts[block.Identifier] = counts.GetValueOrDefault(block.Identifier) + 1;
                    }
                }
            }
        }

        return counts;
    }

    private static bool IsLog(Identifier id) {
        return id.Key.EndsWith("_log", StringComparison.Ordinal)
            || id.Key.EndsWith("_stem", StringComparison.Ordinal);
    }

    private static bool IsLeaves(Identifier id) => id.Key.EndsWith("_leaves", StringComparison.Ordinal);

    private static bool IsPlant(Identifier id) {
        return id.Key is "short_grass" or "tall_grass" or "fern" or "large_fern" or "dandelion"
            or "poppy" or "dead_bush" or "sugar_cane" or "brown_mushroom" or "red_mushroom";
    }

    /// <summary>
    /// A host that never has a neighbouring chunk, so every fork parks. That is the right shape for a
    /// test that generates chunks in isolation: the point is that generating one does not depend on
    /// its neighbours existing.
    /// </summary>
    private sealed class CountingHost : ITerrainHost {
        public event Action<Vec2<int>>? ChunkAvailable {
            add { }
            remove { }
        }

        public int MinY => -64;
        public int MaxY => 320;
        public MinecraftRegistry Registry => VanillaRegistry.Data;

        public bool TryApplyToLoadedChunk(Vec2<int> chunk, Action<ChunkData> apply) => false;
    }
}
