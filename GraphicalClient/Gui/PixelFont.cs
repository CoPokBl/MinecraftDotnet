    private static readonly string[] Missing = ["####", "#..#", "#..#", "#..#", "#..#", "#..#", "####"];

    /// <summary>Atlas cell size: every glyph sits in an 8 by 8 cell, 16 cells to a row.</summary>
    public const int Cell = 8;

    /// <summary>The 128 by 128 RGBA atlas for code points 0 to 255; white ink, transparent paper.</summary>
    public static byte[] BuildAtlas(out int[] widths) {
        widths = new int[256];
        byte[] rgba = new byte[128 * 128 * 4];
        for (int code = 0; code < 256; code++) {
            string[] rows = GlyphFor((char)code);
            int width = rows.Max(r => r.Length);
            widths[code] = width;
            int cellX = code % 16 * Cell, cellY = code / 16 * Cell;
            for (int y = 0; y < rows.Length && y < Rows; y++) {
                for (int x = 0; x < rows[y].Length; x++) {
                    if (rows[y][x] != '#') {
                        continue;
                    }
                    int i = ((cellY + y) * 128 + cellX + x) * 4;
                    rgba[i] = rgba[i + 1] = rgba[i + 2] = rgba[i + 3] = 255;
                }
            }
        }
        return rgba;
    }

    private static string[] GlyphFor(char c) {
        if (Glyphs.TryGetValue(c, out string[]? glyph)) {
            return glyph;
        }
        // Accented Latin letters fall back to their base letter rather than a box.
        string decomposed = c.ToString().Normalize(System.Text.NormalizationForm.FormD);
        if (decomposed.Length > 0 && decomposed[0] != c && Glyphs.TryGetValue(decomposed[0], out glyph)) {
            return glyph;
        }
        return Missing;
    }
