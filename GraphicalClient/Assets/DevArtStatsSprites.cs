    public static TextureImage? Image(string sprite) {
        string name = sprite[Prefix.Length..];
        if (name == "header") {
            return Header();
        }
        return Marks.TryGetValue(name, out string[]? rows) ? Mark(rows) : null;
    }

    private static TextureImage Mark(string[] rows) {
        byte[] rgba = new byte[Size * Size * 4];
        for (int y = 0; y < Size; y++) {
            for (int x = 0; x < Size; x++) {
                uint? argb = rows[y][x] switch {
                    '#' => 0xFF2E2E2E,
                    'o' => 0xFFF2F2F2,
                    '+' => 0xFF8A8A8A,
                    _ => null
                };
                if (argb is { } colour) {
                    DevArt.Put(rgba, y * Size + x, colour);
                }
            }
        }
        return new TextureImage(Size, Size, rgba);
    }

    /// <summary>A cell standing out of the screen, lit from the top left, for the marks to sit on.</summary>
    private static TextureImage Header() {
        byte[] rgba = new byte[Size * Size * 4];
        for (int y = 0; y < Size; y++) {
            for (int x = 0; x < Size; x++) {
                uint rgb = x == Size - 1 || y == Size - 1 ? 0x3C3C3Cu
                    : x == 0 || y == 0 ? 0xF0F0F0u
                    : x == Size - 2 || y == Size - 2 ? 0x8C8C8Cu
                    : 0xC0C0C0u;
                DevArt.Put(rgba, y * Size + x, 0xFF000000 | rgb);
            }
        }
        return new TextureImage(Size, Size, rgba);
    }
